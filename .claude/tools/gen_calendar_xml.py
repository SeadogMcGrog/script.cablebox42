"""Writes the month calendar's skin file (Holidays and specials):
resources/skins/Default/1080i/script-cablebox42-calendar.xml, a 6 x 7 grid of days
filled from window properties by specials_editor.Calendar.

    python .claude/tools/gen_calendar_xml.py

Per cell i (0-41, row by row): B<i> its picture, N<i> the day number, L<i> the star
line; `cur` is the cell under the cursor, `today` today's cell (or empty).
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "resources", "skins", "Default", "1080i", "script-cablebox42-calendar.xml")

LEFT, TOP, W, H, GAP = 40, 232, 257, 130, 6

out = ['''<?xml version="1.0" encoding="UTF-8"?>
<!-- CableBox 42 month calendar (Holidays and specials): generated by .claude/tools/gen_calendar_xml.py,
     driven by window properties from specials_editor.Calendar -->
<window>
    <defaultcontrol>9000</defaultcontrol>
    <backgroundcolor>FF000000</backgroundcolor>
    <controls>
        <control type="image">
            <left>0</left><top>0</top><width>1920</width><height>1080</height>
            <texture>planner_bg.jpg</texture>
        </control>
        <control type="label">
            <left>40</left><top>24</top><width>1840</width><height>70</height>
            <font>font45</font><textcolor>FFFFD24A</textcolor><shadowcolor>FF000000</shadowcolor>
            <label>$INFO[Window.Property(title)]</label>
        </control>
        <control type="label">
            <left>1080</left><top>30</top><width>800</width><height>60</height>
            <align>right</align><font>font12</font><textcolor>FFB8C4E0</textcolor>
            <label>$INFO[Window.Property(hint)]</label>
        </control>
        <control type="label">
            <left>40</left><top>104</top><width>1840</width><height>56</height>
            <font>font27</font><textcolor>FFFFFFFF</textcolor><shadowcolor>FF000000</shadowcolor>
            <label>$INFO[Window.Property(detail)]</label>
        </control>
''']
for c in range(7):
    x = LEFT + c * (W + GAP)
    for sel, color, bold in ((False, "FFB8C4E0", "%s"), (True, "FFFFD24A", "[B]%s[/B]")):
        out.append('''        <control type="label">
            <left>%d</left><top>172</top><width>%d</width><height>50</height>
            <align>center</align><font>font27</font><textcolor>%s</textcolor>
            <label>%s</label>
            <visible>%sString.IsEqual(Window.Property(col),%d)</visible>
        </control>
''' % (x, W, color, bold % ("$INFO[Window.Property(D%d)]" % c), "" if sel else "!", c))
for i in range(42):
    r, c = divmod(i, 7)
    x, y = LEFT + c * (W + GAP), TOP + r * (H + GAP)
    out.append('''        <control type="image">
            <left>%d</left><top>%d</top><width>%d</width><height>%d</height>
            <texture border="6">$INFO[Window.Property(B%d)]</texture>
        </control>
        <control type="label">
            <left>%d</left><top>%d</top><width>%d</width><height>40</height>
            <font>font13</font><textcolor>FFFFFFFF</textcolor>
            <label>$INFO[Window.Property(N%d)]</label>
        </control>
        <control type="label">
            <left>%d</left><top>%d</top><width>%d</width><height>76</height>
            <font>font12</font><textcolor>FFFFFFFF</textcolor><wrapmultiline>true</wrapmultiline>
            <label>$INFO[Window.Property(L%d)]</label>
        </control>
        <control type="image">
            <left>%d</left><top>%d</top><width>%d</width><height>%d</height>
            <texture border="6">calendar_today.png</texture>
            <visible>String.IsEqual(Window.Property(today),%d)</visible>
        </control>
        <control type="image">
            <left>%d</left><top>%d</top><width>%d</width><height>%d</height>
            <texture border="6">planner_cursor.png</texture>
            <visible>String.IsEqual(Window.Property(cur),%d)</visible>
        </control>
''' % (x, y, W, H, i,
       x + 16, y + 6, W - 28, i,
       x + 16, y + 46, W - 28, i,
       x, y, W, H, i,
       x - 3, y - 3, W + 6, H + 6, i))
out.append('''        <control type="button" id="9000">
            <left>-100</left><top>-100</top><width>1</width><height>1</height>
            <texturefocus /><texturenofocus />
        </control>
    </controls>
</window>
''')
io.open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
print(os.path.normpath(OUT))
